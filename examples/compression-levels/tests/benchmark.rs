/// The version of `name` in the workspace's `Cargo.lock`.
fn locked_version(name: &str) -> String {
    let lock = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../Cargo.lock");
    let lock = fs::read_to_string(lock).unwrap_or_default();
    let mut lines = lock.lines();
    while let Some(line) = lines.next() {
        if line == format!("name = \"{name}\"")
            && let Some(version) = lines.next().and_then(|l| l.strip_prefix("version = "))
        {
            return version.trim_matches('"').to_string();
        }
    }
    "unknown".to_string()
}

fn get_cpu_name() -> String {
    #[cfg(target_os = "macos")]
    {
        let output = std::process::Command::new("sysctl")
            .args(["-n", "machdep.cpu.brand_string"])
            .output();
        if let Ok(out) = output {
            return String::from_utf8_lossy(&out.stdout).trim().to_string();
        }
    }
    #[cfg(target_os = "linux")]
    {
        if let Ok(cpuinfo) = std::fs::read_to_string("/proc/cpuinfo")
            && let Some(line) = cpuinfo.lines().find(|l| l.starts_with("model name"))
        {
            return line
                .split(':')
                .nth(1)
                .unwrap_or("unknown")
                .trim()
                .to_string();
        }
    }
    "unknown".to_string()
}

// ---------------------------------------------------------------------------
// Silesia corpus download & load
// ---------------------------------------------------------------------------

/// Where the corpus is cached.
fn silesia_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("target")
        .join("silesia")
}

fn prepare_silesia_data() -> Vec<u8> {
    let cache_dir = silesia_dir();
    fs::create_dir_all(&cache_dir).unwrap();

    let zip_path = cache_dir.join("silesia.zip");

    if !zip_path.exists() {
        eprintln!("Downloading Silesia corpus...");
        download_file(SILESIA_URL, &zip_path);
        eprintln!(
            "Downloaded {} bytes",
            fs::metadata(&zip_path).unwrap().len()
        );
    } else {
        eprintln!("Using cached Silesia corpus");
    }

    // Load entire corpus (no sampling)
    eprintln!("Loading full corpus...");
    let file = fs::File::open(&zip_path).unwrap();
    let mut archive = zip::ZipArchive::new(file).unwrap();
    let mut buffer = Vec::new();

    for i in 0..archive.len() {
        let mut entry = archive.by_index(i).unwrap();
        if !entry.is_file() {
            continue;
        }
        let mut chunk = Vec::new();
        entry.read_to_end(&mut chunk).unwrap();
        buffer.extend_from_slice(&chunk);
    }

    eprintln!("Loaded {:.1} MB", buffer.len() as f64 / (1024.0 * 1024.0));
    buffer
}

fn download_file(url: &str, path: &PathBuf) {
    let response = ureq::get(url).call().unwrap();
    let (_, body) = response.into_parts();
    let mut reader = body.into_reader();
    let mut file = fs::File::create(path).unwrap();
    let mut buf = [0u8; 8192];
    let mut total = 0u64;
    loop {
        let n = reader.read(&mut buf).unwrap();
        if n == 0 {
            break;
        }
        file.write_all(&buf[..n]).unwrap();
        total += n as u64;
        if total % (10 * 1024 * 1024) < 8192 {
            eprint!(
                "\r  {:.1} MB downloaded...",
                total as f64 / (1024.0 * 1024.0)
            );
        }
    }
    eprintln!();
}
